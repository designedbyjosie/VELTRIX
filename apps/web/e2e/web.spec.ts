import { expect, test } from "@playwright/test";
import { markEmailVerified, resetRateLimits } from "./db";

test.beforeEach(async () => {
  await resetRateLimits();
});

test("landing page presents the product and its CTAs", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByRole("heading", { level: 1, name: "Your money. Supercharged." })).toBeVisible();
  await expect(page.getByRole("link", { name: /Get Started Free/ }).first()).toBeVisible();
  await expect(page.getByText("Illustrative preview with sample figures.").first()).toBeVisible();
});

test("register → add account and transaction → budget → dashboard reflects the records", async ({ page }) => {
  const email = `e2e${Date.now()}@example.com`;
  await page.goto("/register");
  await page.fill("#name", "Jordan Lee");
  await page.fill("#email", email);
  await page.fill("#password", "correct horse battery");
  await page.check("input[name=acceptTerms]");
  await page.getByRole("button", { name: "Create account" }).click();

  // Email confirmation gate
  await expect(page.getByRole("heading", { name: "Confirm your email" })).toBeVisible();
  await page.goto("/app");
  await expect(page).toHaveURL(/\/verify-email/);
  await markEmailVerified(email);
  await page.goto("/app");
  await expect(page.getByRole("heading", { name: /Jordan\./ })).toBeVisible();
  await expect(page.getByText("Connect my bank")).toBeVisible();
  await expect(page.getByText("Enter it myself")).toBeVisible();

  // Account
  await page.goto("/app/overview?new=1");
  await page.fill("#acc-name", "Main Checking");
  await page.fill("#acc-bal", "2500.00");
  await page.getByRole("button", { name: "Add account" }).last().click();
  await expect(page.getByText("Main Checking")).toBeVisible();
  await expect(page.getByText("$2,500.00").first()).toBeVisible();

  // Transaction (auto-categorized)
  await page.goto("/app/transactions");
  await page.getByRole("button", { name: "Add", exact: true }).click();
  await page.fill("#t-amount", "84.50");
  await page.fill("#t-merchant", "Whole Foods Market");
  await page.getByRole("button", { name: "Add transaction" }).click();
  await expect(page.getByRole("button", { name: "Whole Foods Market" })).toBeVisible();
  await expect(page.getByRole("combobox", { name: /Category for Whole Foods Market/ })).toHaveValue(/.+/);

  // Budget
  await page.goto("/app/budgets");
  await page.getByRole("button", { name: "New budget" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Category", { exact: true }).selectOption({ label: "Food & Dining" });
  await dialog.getByLabel("Monthly limit").fill("100");
  await dialog.getByRole("button", { name: "Create budget" }).click();
  await expect(page.getByText("$15.50 left · warns at 80%")).toBeVisible();

  // Dashboard
  await page.goto("/app");
  await expect(page.getByText("$2,500.00").first()).toBeVisible();
  await expect(page.getByText("$84.50").first()).toBeVisible();

  // Advisor answers from the data without an AI key
  await page.goto("/app/advisor");
  await page.getByRole("button", { name: "Which categories are over budget?" }).click();
  await expect(page.getByText(/Food & Dining: \$84\.50 of \$100\.00/)).toBeVisible();
  await expect(page.getByText("Generated by VELTRIX's built-in analysis.")).toBeVisible();
});

test("guided manual setup, then the advisor adjusts the dashboard after approval", async ({ page }) => {
  const email = `e2e-setup-${Date.now()}@example.com`;
  await page.goto("/register");
  await page.fill("#name", "Riley Setup");
  await page.fill("#email", email);
  await page.fill("#password", "correct horse battery staple");
  await page.check("input[name=acceptTerms]");
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page.getByRole("heading", { name: "Confirm your email" })).toBeVisible();
  await markEmailVerified(email);

  await page.goto("/app");
  await page.getByText("Enter it myself").click();
  await page.fill("#acc-bal-1", "1,250");
  await page.getByRole("button", { name: "Continue" }).click();
  await page.fill("#income", "3000");
  await page.getByRole("button", { name: "Continue" }).click();
  await page.fill("#b-housing", "1200");
  await page.fill("#b-food", "400");
  await expect(page.getByText("Leaves $1,400 for saving and extras")).toBeVisible();
  await page.getByRole("button", { name: "Continue" }).click();
  await expect(page.locator("#g-target")).toHaveValue("4800.00");
  await page.fill("#g-monthly", "200");
  await page.getByRole("button", { name: "Continue" }).click();
  await expect(page.getByText("Left over each month after budget and goal saving: $1,200")).toBeVisible();
  await page.getByRole("button", { name: "Finish setup" }).click();

  await expect(page.getByRole("heading", { name: "Monthly plan" })).toBeVisible();
  await expect(page.getByText("Unplanned each month")).toBeVisible();

  await page.goto("/app/advisor");
  await page.fill("#advisor-input", "Set my food budget to $500 and hide investments from my dashboard");
  await page.keyboard.press("Enter");
  await expect(page.getByText("Set your Food & Dining budget to $500.00 a month (now $400.00)").last()).toBeVisible();
  await page.getByRole("button", { name: "Apply all" }).click();
  await expect(page.getByText("Applied", { exact: true })).toHaveCount(2);

  await page.goto("/app");
  await expect(page.getByRole("heading", { name: "Monthly plan" })).toBeVisible();
  await expect(page.getByText("Investment performance")).toHaveCount(0);
  await expect(page.getByText("$1,100").first()).toBeVisible();
});

test("password reset page never reveals whether an account exists", async ({ page }) => {
  await page.goto("/login");
  await page.getByRole("link", { name: "Forgot password?" }).click();
  await expect(page.getByRole("heading", { name: "Reset your password" })).toBeVisible();
  await page.fill("#email", `nobody${Date.now()}@example.com`);
  await page.getByRole("button", { name: "Send reset link" }).click();
  await expect(page.getByText("If an account exists for that address")).toBeVisible();
});

